"""Regression tests against a disposable local PostgreSQL container.
Run: PG_CONTAINER=cloble-nadhif-audit-pg python3 test_discover_match_audit.py
The named cloble-* container must be disposable; no Supabase credentials are used.
"""
from pathlib import Path
import concurrent.futures
import json
import os
import re
import subprocess
import threading

ROOT = Path(__file__).resolve().parents[3]
CONTAINER = os.environ['PG_CONTAINER']
assert CONTAINER.startswith('cloble-'), 'Use a disposable cloble-* PostgreSQL container'
DATABASE = 'nadhif_audit_' + str(os.getpid())


def query(sql, database=DATABASE):
    result = subprocess.run(['podman', 'exec', '-i', CONTAINER, 'psql', '-X', '-qAt',
                             '-U', 'postgres', '-d', database, '-v', 'ON_ERROR_STOP=1'],
                            input=sql, capture_output=True, text=True, timeout=25)
    assert result.returncode == 0, result.stderr
    return result.stdout.strip()


def rpc(user, name, *args):
    def literal(value):
        if value is None:
            return 'NULL'
        if isinstance(value, int):
            return str(value)
        return "'" + value.replace("'", "''") + "'"
    return json.loads(query(f"SET test.user_id='{user}'; SELECT public.{name}({','.join(map(literal, args))});"))


def expect(result, code='SUCCESS'):
    assert result['code'] == code, result
    return result


def seed():
    query('''TRUNCATE notifications,matches,interests,swipe_passes,clothing_items,users RESTART IDENTITY CASCADE;
    INSERT INTO users(id,name) VALUES (1,'A'),(2,'B'),(3,'C'),(4,'D');
    INSERT INTO clothing_items(id,"ownerId",name,gender)
    SELECT u.id*100+i,u.id,'Item '||u.name||i,(ARRAY['Pria','Wanita','Uniseks'])[1+(i-1)%3]
    FROM users u CROSS JOIN generate_series(1,5) i;''')


def offer(sender, item):
    receiver = item // 100
    return int(query(f'''INSERT INTO interests("senderUserId","receiverUserId","targetItemId",status,"createdAt")
        VALUES ({sender},{receiver},{item},'PENDING',extract(epoch from clock_timestamp())::bigint*1000)
        RETURNING id;'''))


def notification(interest, read=False):
    return int(query(f'''INSERT INTO notifications("userId",type,"relatedInterestId","isRead")
        SELECT "receiverUserId",'INCOMING_INTEREST',id,{str(read).lower()} FROM interests WHERE id={interest} RETURNING id;'''))


def respond(user, interest, item):
    return expect(rpc(user, 'rpc_respond_to_interest_and_create_match', user, interest, item))['matchId']


def latest_function(name):
    matches = []
    for path in sorted((ROOT / 'supabase/migrations').glob('*.sql')):
        if path.name.startswith('20261124'):
            continue
        matches += re.findall(r'CREATE OR REPLACE FUNCTION public\.' + name + r'\([\s\S]*?\n\$\$;', path.read_text())
    return matches[-1]


