CREATE TABLE public.users (id bigint PRIMARY KEY, name text);
CREATE TABLE public.clothing_items (id bigint PRIMARY KEY, "ownerId" bigint REFERENCES users(id), name text, status text NOT NULL DEFAULT 'AVAILABLE', "isBarterAllowed" boolean NOT NULL DEFAULT true, "updatedAt" bigint);
CREATE TABLE public.interests (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "senderUserId" bigint REFERENCES users(id), "receiverUserId" bigint REFERENCES users(id), "targetItemId" bigint REFERENCES clothing_items(id), status text NOT NULL CHECK (status IN ('PENDING','ACCEPTED_MATCHED','RESOLVED_BY_MATCH','DECLINED','INVALIDATED')), "createdAt" bigint, "respondedAt" bigint);
CREATE UNIQUE INDEX index_interests_active_sender_target ON interests("senderUserId","targetItemId") WHERE status='PENDING';
CREATE TABLE public.matches (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "sourceInterestId" bigint REFERENCES interests(id), "user1Id" bigint REFERENCES users(id), "user1ItemId" bigint NOT NULL REFERENCES clothing_items(id), "user2Id" bigint REFERENCES users(id), "user2ItemId" bigint NOT NULL REFERENCES clothing_items(id), status text NOT NULL CHECK (status IN ('ACTIVE','COMPLETED','CANCELLED')), "meetingLocation" text, "createdAt" bigint, "updatedAt" bigint);
CREATE UNIQUE INDEX index_matches_sourceinterestid ON matches("sourceInterestId");
CREATE UNIQUE INDEX index_matches_unique_active_user_pair ON matches(LEAST("user1Id","user2Id"),GREATEST("user1Id","user2Id")) WHERE status='ACTIVE';
CREATE TABLE public.notifications (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "userId" bigint, type text, title text, body text, "relatedInterestId" bigint, "relatedMatchId" bigint, "isRead" boolean, "createdAt" bigint);
CREATE TABLE public.swipe_passes ("userId" bigint, "targetItemId" bigint);
CREATE FUNCTION public.current_session_user_id() RETURNS bigint LANGUAGE sql AS $$ SELECT nullif(current_setting('test.user_id', true), '')::bigint $$;

CREATE OR REPLACE FUNCTION public.rpc_respond_to_interest_and_create_match(p_actor_user_id bigint, p_interest_id bigint, p_chosen_sender_item_id bigint, p_now_millis bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER AS $function$
DECLARE
    v_session_user_id BIGINT;
    v_interest public.interests%ROWTYPE;
    v_target_item public.clothing_items%ROWTYPE;
    v_chosen_item public.clothing_items%ROWTYPE;
    v_active_either_count INTEGER;
    v_pair_history_count INTEGER;
    v_active_user_pair_count INTEGER;
    v_actor_name TEXT;
    v_sender_name TEXT;
    v_match_id BIGINT;
BEGIN
    v_session_user_id := public.current_session_user_id();
    IF v_session_user_id IS NULL OR v_session_user_id <> p_actor_user_id THEN
        RETURN jsonb_build_object('code', 'INVALID_ITEM_OWNERSHIP');
    END IF;
    SELECT * INTO v_interest FROM public.interests WHERE id = p_interest_id FOR UPDATE;
    IF NOT FOUND OR v_interest."receiverUserId" <> p_actor_user_id OR v_interest.status <> 'PENDING' THEN
        RETURN jsonb_build_object('code', 'INTEREST_ALREADY_PROCESSED_OR_INVALID');
    END IF;
    SELECT * INTO v_target_item FROM public.clothing_items WHERE id = v_interest."targetItemId" FOR UPDATE;
    IF NOT FOUND THEN
        UPDATE public.interests SET status='INVALIDATED', "respondedAt"=p_now_millis WHERE id=v_interest.id;
        RETURN jsonb_build_object('code','TARGET_ITEM_NOT_FOUND','invalidated',TRUE);
    END IF;
    IF v_target_item."ownerId" <> p_actor_user_id OR p_actor_user_id = v_interest."senderUserId" THEN
        RETURN jsonb_build_object('code','INVALID_ITEM_OWNERSHIP');
    END IF;
    IF v_target_item.status <> 'AVAILABLE' THEN
        UPDATE public.interests SET status='INVALIDATED', "respondedAt"=p_now_millis WHERE id=v_interest.id;
        RETURN jsonb_build_object('code','TARGET_ITEM_UNAVAILABLE','invalidated',TRUE);
    END IF;
    SELECT * INTO v_chosen_item FROM public.clothing_items WHERE id=p_chosen_sender_item_id FOR UPDATE;
    IF NOT FOUND THEN RETURN jsonb_build_object('code','CHOSEN_ITEM_NOT_FOUND'); END IF;
    IF v_chosen_item."ownerId" <> v_interest."senderUserId" THEN RETURN jsonb_build_object('code','INVALID_ITEM_OWNERSHIP'); END IF;
    IF v_chosen_item.status <> 'AVAILABLE' THEN RETURN jsonb_build_object('code','CHOSEN_ITEM_UNAVAILABLE'); END IF;
    IF NOT v_target_item."isBarterAllowed" OR NOT v_chosen_item."isBarterAllowed" THEN RETURN jsonb_build_object('code','BARTER_NOT_ALLOWED'); END IF;
    SELECT COUNT(*) INTO v_active_either_count FROM public.matches WHERE status='ACTIVE' AND ("user1ItemId" IN (v_target_item.id,v_chosen_item.id) OR "user2ItemId" IN (v_target_item.id,v_chosen_item.id));
    IF v_active_either_count > 0 THEN RETURN jsonb_build_object('code','ITEM_ALREADY_IN_ACTIVE_MATCH'); END IF;
    SELECT COUNT(*) INTO v_pair_history_count FROM public.matches WHERE status IN ('ACTIVE','COMPLETED') AND (("user1ItemId"=v_target_item.id AND "user2ItemId"=v_chosen_item.id) OR ("user1ItemId"=v_chosen_item.id AND "user2ItemId"=v_target_item.id));
    IF v_pair_history_count > 0 THEN RETURN jsonb_build_object('code','PAIR_ALREADY_MATCHED'); END IF;
    SELECT COUNT(*) INTO v_active_user_pair_count
    FROM public.matches
    WHERE status = 'ACTIVE'
      AND (("user1Id" = p_actor_user_id AND "user2Id" = v_interest."senderUserId")
        OR ("user1Id" = v_interest."senderUserId" AND "user2Id" = p_actor_user_id));
    IF v_active_user_pair_count > 0 THEN
        RETURN jsonb_build_object('code', 'PAIR_ALREADY_MATCHED');
    END IF;
    SELECT COALESCE(name,'') INTO v_actor_name FROM public.users WHERE id=p_actor_user_id;
    SELECT COALESCE(name,'') INTO v_sender_name FROM public.users WHERE id=v_interest."senderUserId";
    INSERT INTO public.matches ("sourceInterestId","user1Id","user1ItemId","user2Id","user2ItemId",status,"meetingLocation","createdAt","updatedAt") VALUES (v_interest.id,p_actor_user_id,v_target_item.id,v_interest."senderUserId",v_chosen_item.id,'ACTIVE',NULL,p_now_millis,p_now_millis) RETURNING id INTO v_match_id;
    UPDATE public.interests SET status='ACCEPTED_MATCHED',"respondedAt"=p_now_millis WHERE id=v_interest.id;
    UPDATE public.interests SET status='RESOLVED_BY_MATCH',"respondedAt"=p_now_millis WHERE "senderUserId"=p_actor_user_id AND "receiverUserId"=v_interest."senderUserId" AND "targetItemId"=v_chosen_item.id AND status='PENDING';
    INSERT INTO public.notifications ("userId",type,title,body,"relatedInterestId","relatedMatchId","isRead","createdAt") VALUES
      (v_interest."senderUserId",'MATCH_VERIFIED','Match terverifikasi dengan '||v_actor_name,v_target_item.name||' - '||v_chosen_item.name||' siap didiskusikan di ruang Chat.',v_interest.id,v_match_id,FALSE,p_now_millis),
      (p_actor_user_id,'MATCH_VERIFIED','Match terverifikasi dengan '||v_sender_name,v_target_item.name||' - '||v_chosen_item.name||' siap didiskusikan di ruang Chat.',v_interest.id,v_match_id,FALSE,p_now_millis);
    RETURN jsonb_build_object('code','SUCCESS','matchId',v_match_id);
END;
$function$;

CREATE OR REPLACE FUNCTION public.rpc_send_interest(p_sender_user_id bigint, p_target_item_id bigint, p_now_millis bigint, p_delete_swipe_pass boolean DEFAULT false)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER AS $function$
DECLARE
    v_session_user_id BIGINT;
    v_sender public.users%ROWTYPE;
    v_target public.clothing_items%ROWTYPE;
    v_existing public.interests%ROWTYPE;
    v_non_cancelled_match_count INTEGER;
    v_eligible_count INTEGER;
    v_active_match_count INTEGER;
    v_interest_id BIGINT;
    v_reverse_interest public.interests%ROWTYPE;
    v_reverse_item public.clothing_items%ROWTYPE;
    v_reverse_active_match INTEGER;
    v_pair_history_count INTEGER;
    v_active_user_pair_count INTEGER;
    v_target_owner_name TEXT;
    v_match_id BIGINT;
BEGIN
    v_session_user_id := public.current_session_user_id();
    IF v_session_user_id IS NULL OR v_session_user_id <> p_sender_user_id THEN RETURN jsonb_build_object('code','SENDER_NOT_FOUND'); END IF;
    SELECT * INTO v_sender FROM public.users WHERE id=p_sender_user_id;
    IF NOT FOUND THEN RETURN jsonb_build_object('code','SENDER_NOT_FOUND'); END IF;
    SELECT * INTO v_target FROM public.clothing_items WHERE id=p_target_item_id FOR UPDATE;
    IF NOT FOUND THEN RETURN jsonb_build_object('code','TARGET_ITEM_NOT_FOUND'); END IF;
    IF v_target."ownerId"=p_sender_user_id THEN RETURN jsonb_build_object('code','CANNOT_INTEREST_OWN_ITEM'); END IF;
    SELECT COUNT(*) INTO v_active_user_pair_count
    FROM public.matches
    WHERE status = 'ACTIVE'
      AND (("user1Id" = p_sender_user_id AND "user2Id" = v_target."ownerId")
        OR ("user1Id" = v_target."ownerId" AND "user2Id" = p_sender_user_id));
    IF v_active_user_pair_count > 0 THEN
        RETURN jsonb_build_object('code', 'PAIR_ALREADY_MATCHED');
    END IF;
    FOR v_existing IN SELECT * FROM public.interests WHERE "senderUserId"=p_sender_user_id AND "targetItemId"=p_target_item_id ORDER BY "createdAt" DESC LOOP
        IF v_existing.status IN ('PENDING','DECLINED') THEN RETURN jsonb_build_object('code','ALREADY_INTERESTED','existingStatus',v_existing.status);
        ELSIF v_existing.status IN ('ACCEPTED_MATCHED','RESOLVED_BY_MATCH') THEN
            SELECT COUNT(*) INTO v_non_cancelled_match_count FROM public.matches m WHERE m.status IN ('ACTIVE','COMPLETED') AND (m."sourceInterestId"=v_existing.id OR ((m."user1ItemId"=p_target_item_id OR m."user2ItemId"=p_target_item_id) AND (m."user1Id"=p_sender_user_id OR m."user2Id"=p_sender_user_id)));
            IF v_non_cancelled_match_count > 0 THEN RETURN jsonb_build_object('code','ALREADY_INTERESTED','existingStatus',v_existing.status); END IF;
        END IF;
    END LOOP;
    SELECT COUNT(*) INTO v_eligible_count FROM public.clothing_items c WHERE c."ownerId"=p_sender_user_id AND c.status='AVAILABLE' AND c."isBarterAllowed"=TRUE AND c.id NOT IN (SELECT "user1ItemId" FROM public.matches WHERE status='ACTIVE' UNION SELECT "user2ItemId" FROM public.matches WHERE status='ACTIVE');
    IF v_eligible_count=0 THEN RETURN jsonb_build_object('code','REQUIRES_BARTERABLE_ITEM'); END IF;
    SELECT COUNT(*) INTO v_active_match_count FROM public.matches WHERE status='ACTIVE' AND ("user1ItemId"=p_target_item_id OR "user2ItemId"=p_target_item_id);
    IF v_target.status<>'AVAILABLE' OR NOT v_target."isBarterAllowed" OR v_active_match_count>0 THEN RETURN jsonb_build_object('code','TARGET_ITEM_NOT_ELIGIBLE'); END IF;
    SELECT * INTO v_reverse_interest
    FROM public.interests
    WHERE "senderUserId" = v_target."ownerId"
      AND "receiverUserId" = p_sender_user_id
      AND status = 'PENDING'
    ORDER BY "createdAt" DESC
    LIMIT 1
    FOR UPDATE;
    IF FOUND THEN
        SELECT * INTO v_reverse_item FROM public.clothing_items WHERE id=v_reverse_interest."targetItemId" FOR UPDATE;
        IF FOUND AND v_reverse_item."ownerId"=p_sender_user_id AND v_reverse_item.status='AVAILABLE' AND v_reverse_item."isBarterAllowed"=TRUE THEN
            SELECT COUNT(*) INTO v_reverse_active_match FROM public.matches WHERE status='ACTIVE' AND ("user1ItemId"=v_reverse_item.id OR "user2ItemId"=v_reverse_item.id);
            SELECT COUNT(*) INTO v_pair_history_count FROM public.matches WHERE status IN ('ACTIVE','COMPLETED') AND (("user1ItemId"=v_target.id AND "user2ItemId"=v_reverse_item.id) OR ("user1ItemId"=v_reverse_item.id AND "user2ItemId"=v_target.id));
            IF v_reverse_active_match=0 AND v_pair_history_count=0 THEN
                SELECT COALESCE(name,'Pengguna') INTO v_target_owner_name FROM public.users WHERE id=v_target."ownerId";
                INSERT INTO public.interests ("senderUserId","receiverUserId","targetItemId",status,"createdAt","respondedAt") VALUES (p_sender_user_id,v_target."ownerId",p_target_item_id,'RESOLVED_BY_MATCH',p_now_millis,p_now_millis) RETURNING id INTO v_interest_id;
                UPDATE public.interests SET status='ACCEPTED_MATCHED',"respondedAt"=p_now_millis WHERE id=v_reverse_interest.id;
                INSERT INTO public.matches ("sourceInterestId","user1Id","user1ItemId","user2Id","user2ItemId",status,"meetingLocation","createdAt","updatedAt") VALUES (v_reverse_interest.id,v_target."ownerId",v_target.id,p_sender_user_id,v_reverse_item.id,'ACTIVE',NULL,p_now_millis,p_now_millis) RETURNING id INTO v_match_id;
                INSERT INTO public.notifications ("userId",type,title,body,"relatedInterestId","relatedMatchId","isRead","createdAt") VALUES
                  (v_target."ownerId",'MATCH_VERIFIED','Match terverifikasi dengan '||v_sender.name,v_target.name||' - '||v_reverse_item.name||' siap didiskusikan di ruang Chat.',v_reverse_interest.id,v_match_id,FALSE,p_now_millis),
                  (p_sender_user_id,'MATCH_VERIFIED','Match terverifikasi dengan '||v_target_owner_name,v_reverse_item.name||' - '||v_target.name||' siap didiskusikan di ruang Chat.',v_interest_id,v_match_id,FALSE,p_now_millis);
                IF p_delete_swipe_pass THEN DELETE FROM public.swipe_passes WHERE "userId"=p_sender_user_id AND "targetItemId"=p_target_item_id; END IF;
                RETURN jsonb_build_object('code','SUCCESS','interestId',v_interest_id,'isMutualMatch',TRUE,'matchId',v_match_id);
            END IF;
        END IF;
    END IF;
    INSERT INTO public.interests ("senderUserId","receiverUserId","targetItemId",status,"createdAt","respondedAt") VALUES (p_sender_user_id,v_target."ownerId",p_target_item_id,'PENDING',p_now_millis,NULL) RETURNING id INTO v_interest_id;
    INSERT INTO public.notifications ("userId",type,title,body,"relatedInterestId","relatedMatchId","isRead","createdAt") VALUES (v_target."ownerId",'INCOMING_INTEREST',v_sender.name||' tertarik pada '||v_target.name,'Buka lemari '||v_sender.name||' dan pilih tepat satu pakaian berizin barter.',v_interest_id,NULL,FALSE,p_now_millis);
    IF p_delete_swipe_pass THEN DELETE FROM public.swipe_passes WHERE "userId"=p_sender_user_id AND "targetItemId"=p_target_item_id; END IF;
    RETURN jsonb_build_object('code','SUCCESS','interestId',v_interest_id,'isMutualMatch',FALSE);
END;
$function$;

CREATE FUNCTION public.rpc_cancel_match(p_match_id bigint, p_actor_user_id bigint, p_now_millis bigint) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER AS $function$
DECLARE
    v_session_user_id bigint; v_match public.matches%ROWTYPE; v_counterpart_id bigint;
BEGIN
    v_session_user_id := public.current_session_user_id();
    IF v_session_user_id IS NULL OR v_session_user_id <> p_actor_user_id THEN RETURN jsonb_build_object('code','NOT_MATCH_PARTICIPANT'); END IF;
    SELECT * INTO v_match FROM public.matches WHERE id=p_match_id FOR UPDATE;
    IF NOT FOUND THEN RETURN jsonb_build_object('code','MATCH_NOT_FOUND'); END IF;
    IF p_actor_user_id<>v_match."user1Id" AND p_actor_user_id<>v_match."user2Id" THEN RETURN jsonb_build_object('code','NOT_MATCH_PARTICIPANT'); END IF;
    IF v_match.status<>'ACTIVE' THEN RETURN jsonb_build_object('code','MATCH_NOT_ACTIVE','currentStatus',v_match.status); END IF;
    UPDATE public.matches SET status='CANCELLED',"updatedAt"=p_now_millis WHERE id=p_match_id;
    v_counterpart_id := CASE WHEN p_actor_user_id=v_match."user1Id" THEN v_match."user2Id" ELSE v_match."user1Id" END;
    INSERT INTO public.notifications ("userId",type,title,body,"relatedInterestId","relatedMatchId","isRead","createdAt") VALUES (v_counterpart_id,'MATCH_CANCELLED','Match dibatalkan','Rekan barter membatalkan Match.',v_match."sourceInterestId",p_match_id,FALSE,p_now_millis);
    RETURN jsonb_build_object('code','SUCCESS');
END;
$function$;
CREATE FUNCTION public.rpc_complete_match_exchange(p_match_id bigint,p_actor_user_id bigint,p_meeting_location text,p_now_millis bigint) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER AS $function$
DECLARE
    v_session_user_id bigint; v_match public.matches%ROWTYPE; v_item1 public.clothing_items%ROWTYPE; v_item2 public.clothing_items%ROWTYPE; v_counterpart_id bigint;
BEGIN
    v_session_user_id := public.current_session_user_id();
    IF v_session_user_id IS NULL OR v_session_user_id<>p_actor_user_id THEN RETURN jsonb_build_object('code','NOT_MATCH_PARTICIPANT'); END IF;
    SELECT * INTO v_match FROM public.matches WHERE id=p_match_id FOR UPDATE;
    IF NOT FOUND THEN RETURN jsonb_build_object('code','MATCH_NOT_FOUND'); END IF;
    IF p_actor_user_id<>v_match."user1Id" AND p_actor_user_id<>v_match."user2Id" THEN RETURN jsonb_build_object('code','NOT_MATCH_PARTICIPANT'); END IF;
    IF v_match.status<>'ACTIVE' THEN RETURN jsonb_build_object('code','MATCH_NOT_ACTIVE','currentStatus',v_match.status); END IF;
    SELECT * INTO v_item1 FROM public.clothing_items WHERE id=v_match."user1ItemId" FOR UPDATE;
    SELECT * INTO v_item2 FROM public.clothing_items WHERE id=v_match."user2ItemId" FOR UPDATE;
    IF v_item1.id IS NULL OR v_item2.id IS NULL OR v_item1.status<>'AVAILABLE' OR v_item2.status<>'AVAILABLE' THEN RETURN jsonb_build_object('code','ITEMS_NO_LONGER_AVAILABLE'); END IF;
    UPDATE public.matches SET status='COMPLETED',"meetingLocation"=NULLIF(BTRIM(p_meeting_location),''),"updatedAt"=p_now_millis WHERE id=p_match_id;
    UPDATE public.clothing_items SET status='EXCHANGED',"updatedAt"=p_now_millis WHERE id IN (v_match."user1ItemId",v_match."user2ItemId");
    UPDATE public.interests SET status='INVALIDATED',"respondedAt"=p_now_millis WHERE "targetItemId" IN (v_match."user1ItemId",v_match."user2ItemId") AND status='PENDING';
    v_counterpart_id := CASE WHEN p_actor_user_id=v_match."user1Id" THEN v_match."user2Id" ELSE v_match."user1Id" END;
    INSERT INTO public.notifications ("userId",type,title,body,"relatedInterestId","relatedMatchId","isRead","createdAt") VALUES (v_counterpart_id,'EXCHANGE_COMPLETED','Pertukaran selesai','Pasangan pakaian telah ditandai sudah ditukar. Berikan rating & ulasan.',v_match."sourceInterestId",p_match_id,FALSE,p_now_millis);
    RETURN jsonb_build_object('code','SUCCESS');
END;
$function$;
